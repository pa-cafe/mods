import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, existsSync, rmSync, readdirSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';

function fixture(t) {
  const root = mkdtempSync(path.join(tmpdir(), 'pa installer '));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const repo = path.join(root, 'original checkout');
  const home = path.join(root, 'Herdr profile');
  const bin = path.join(root, 'bin');
  const user = path.join(root, 'home');
  const here = 'connectors/herdr-desktop';
  const mod = path.join(repo, here, 'pacafe-desktop');
  const xdg = path.join(root, 'xdg');
  const log = path.join(root, 'check-log');
  for (const p of [mod, home, bin, user]) mkdirSync(p, { recursive: true });
  const env = { ...process.env, HOME: user, HERDR_APP_HOME: home, XDG_CONFIG_HOME: xdg,
    PA_FIXTURE_REAL_HOME: home, PA_FIXTURE_LOG: log, PATH: bin + path.delimiter + process.env.PATH };
  const call = (exe, args, opts = {}) => spawnSync(exe, args, { encoding: 'utf8', cwd: repo, env, ...opts });
  const checked = result => { assert.equal(result.status, 0, result.stderr); return result.stdout.trim(); };
  const git = (...args) => checked(call('git', args));
  git('init', '-b', 'main');
  git('config', 'user.name', 'PA Cafe Test');
  git('config', 'user.email', 'synthetic@example.test');
  copyFileSync(new URL('../install.sh', import.meta.url), path.join(repo, here, 'install.sh'));
  const write = (p, value) => writeFileSync(path.join(mod, p), value);
  const commit = message => {
    git('add', '.');
    git('commit', '-m', message);
    return git('rev-parse', 'HEAD');
  };
  write('mod.json', '{"place":"none"}');
  write('main.js', 'first\n');
  write('obsolete.js', 'obsolete\n');
  writeFileSync(path.join(repo, 'not-in-the-mod.txt'), 'internal test');
  const first = commit('first');
  writeFileSync(path.join(bin, 'herdr-app'), `#!/bin/bash
set -eu
[[ "$1" == check && "$HERDR_APP_HOME" != "$PA_FIXTURE_REAL_HOME" && "$HOME" != "$PA_FIXTURE_REAL_HOME" ]]
[[ -f "$2/mod.json" && -f "$2/main.js" ]]
printf '%s\\n' "$HERDR_APP_HOME" >> "$PA_FIXTURE_LOG"
[[ \${PA_FIXTURE_CHECK_FAIL-} != 1 ]] || exit 9
printf 'generated by check' > "$2/generated.d.ts"
`, { mode: 0o700 });
  const install = (args = [], overrides = {}, cwd = repo) =>
    call('/bin/bash', [path.join(cwd, here, 'install.sh'), ...args], { cwd, env: { ...env, ...overrides } });
  const installPath = path.join(home, 'mods/pacafe-desktop');
  const read = p => readFileSync(p, 'utf8');
  return { here, root, repo, home, bin, env, xdg, log, mod, write, install, installPath, read, checked, git, first, commit, call };
}

test('installs only the committed bundle, updates it, and preserves layouts, data and other mods', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const files = ['layouts/main.json', 'data/pacafe-desktop-link/connection.json', 'mods/another-mod/main.js'];
  for (const name of files) {
    const p = path.join(f.home, name);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, name);
  }
  f.write('main.js', 'dirty worktree\n');
  assert.match(f.checked(f.install()), new RegExp(f.first));
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'first\n');
  assert.equal(f.read(path.join(f.installPath, '.pacafe-source-commit')).trim(), f.first);
  assert.equal(existsSync(path.join(f.installPath, 'not-in-the-mod.txt')), false);
  assert.equal(existsSync(path.join(f.installPath, 'generated.d.ts')), false);
  assert.match(f.read(f.log), /^\/tmp\/pacafe-check\./);
  f.write('main.js', 'second\n');
  rmSync(path.join(f.mod, 'obsolete.js'));
  const second = f.commit('second');
  assert.match(f.checked(f.install()), new RegExp(second));
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'second\n');
  assert.equal(existsSync(path.join(f.installPath, 'obsolete.js')), false);
  const backup = readdirSync(f.home).find(name => name.startsWith('.pacafe-desktop-backup.'));
  assert.equal(f.read(path.join(f.home, backup, 'pacafe-desktop/main.js')), 'first\n');
  for (const name of files) assert.equal(f.read(path.join(f.home, name)), name);
  f.checked(f.install(['--ref', f.first]));
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'first\n');
});

test('does not replace a mod after failed validation and restores it if activation fails', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  f.checked(f.install());
  f.write('main.js', 'second\n');
  f.commit('second');
  assert.match(f.install([], { PA_FIXTURE_CHECK_FAIL: '1' }).stderr, /nothing was installed/);
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'first\n');
  writeFileSync(path.join(f.bin, 'mv'), `#!/bin/bash
case "$1" in */.pacafe-desktop-install.*/pacafe-desktop) exit 12 ;; esac
exec /bin/mv "$@"
`, { mode: 0o700 });
  assert.equal(f.install().status, 12);
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'first\n');
  assert.equal(existsSync(path.join(f.home, '.pacafe-desktop-install.lock')), false);
});

test('update fetches main without overwriting checkout edits and honors the XDG profile default', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const clone = path.join(f.root, 'clone for installing');
  f.git('clone', '--no-local', f.repo, clone);
  writeFileSync(path.join(clone, f.here, 'pacafe-desktop/main.js'), 'local uncommitted work\n');
  f.write('main.js', 'second\n');
  const second = f.commit('second');
  const actualProfile = path.join(f.xdg, 'herdr-app');
  assert.match(f.checked(f.install(['--update'], { HERDR_APP_HOME: '', PA_FIXTURE_REAL_HOME: actualProfile }, clone)), new RegExp(second));
  assert.equal(f.read(path.join(clone, f.here, 'pacafe-desktop/main.js')), 'local uncommitted work\n');
  assert.equal(f.read(path.join(actualProfile, 'mods/pacafe-desktop/main.js')), 'second\n');
  assert.equal(f.checked(f.call('git', ['-C', clone, 'rev-parse', 'HEAD'])), f.first);
  assert.deepEqual(readdirSync(f.home), []);
});

test('refuses candidate and destination symlinks instead of following them', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const alternate = path.join(f.root, 'do not touch');
  mkdirSync(alternate);
  const marker = path.join(alternate, 'main.js');
  writeFileSync(marker, 'untouched\n');
  mkdirSync(path.dirname(f.installPath), { recursive: true });
  symlinkSync(alternate, f.installPath);
  const rejected = f.install();
  assert.notEqual(rejected.status, 0);
  assert.match(rejected.stderr, /linked mods directory/);
  assert.equal(f.read(marker), 'untouched\n');
  symlinkSync(marker, path.join(f.mod, 'escape.js'));
  f.commit('with unsafe link');
  const rejectedTree = f.install();
  assert.notEqual(rejectedTree.status, 0);
  assert.match(rejectedTree.stderr, /symlink or submodule/);
});

test('the documented one-paste bootstrap diagnoses missing Git and installs from an authenticated-style clone', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const readme = readFileSync(new URL('../README.md', import.meta.url), 'utf8');
  const command = readme.match(/```bash\n(bash -c '[^\n]+')\n```/)[1].match(/^bash -c '(.+)'$/)[1];
  const noGit = f.call('/bin/bash', ['-c', command], { env: { PATH: f.bin } });
  assert.equal(noGit.status, 1);
  assert.match(noGit.stderr, /Install Git first/);
  assert.equal(existsSync(f.installPath), false);

  const gitConfig = {
    GIT_CONFIG_COUNT: '1',
    GIT_CONFIG_KEY_0: `url.file://${f.repo}.insteadOf`,
    GIT_CONFIG_VALUE_0: 'https://github.com/pa-cafe/mods.git',
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_CONFIG_GLOBAL: '/dev/null',
    TMPDIR: f.root,
  };
  const clone = f.call('/bin/bash', ['-c', command], { env: { ...f.env, ...gitConfig } });
  assert.match(f.checked(clone), new RegExp(f.first));
  assert.equal(f.read(path.join(f.installPath, 'main.js')), 'first\n');
  assert.equal(readdirSync(f.root).some(name => name.startsWith('pacafe-install.')), false);
});

test('Windows profile resolution is isolated and missing optional runtimes still stage only the mod', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const windowsHome = path.join(f.root, 'windows-user');
  const windowsDestination = path.join(f.root, 'windows-custom-profile');
  const missingBin = path.join(f.root, 'windows-tools');
  mkdirSync(missingBin);
  const shellTools = ['git', 'tar', 'grep', 'mktemp', 'dirname', 'mkdir', 'rm', 'mv', 'rmdir'];
  for (const tool of shellTools) {
    const executable = f.checked(f.call('/bin/bash', ['-c', 'command -v "$1"', 'bash', tool]));
    symlinkSync(executable, path.join(missingBin, tool));
  }
  writeFileSync(path.join(missingBin, 'uname'), '#!/bin/bash\nprintf "MINGW64_NT-10.0\\n"\n', { mode: 0o700 });
  writeFileSync(path.join(missingBin, 'cygpath'), `#!/bin/bash
case "$3" in
  'C:\\Users\\Fixture') printf '%s\\n' "$FIXTURE_WINDOWS_HOME" ;;
  'C:\\Users\\Fixture\\PA Cafe profile') printf '%s\\n' "$FIXTURE_WINDOWS_DESTINATION" ;;
  *) printf '%s\\n' "$3" ;;
esac
`, { mode: 0o700 });
  const env = { PATH: missingBin, USERPROFILE: 'C:\\Users\\Fixture', LOCALAPPDATA: '',
    FIXTURE_WINDOWS_HOME: windowsHome, FIXTURE_WINDOWS_DESTINATION: windowsDestination, HERDR_APP_HOME: '', XDG_CONFIG_HOME: '' };
  const windows = f.install([], env);
  assert.match(f.checked(windows), /Native check skipped because Herdr Desktop is missing/);
  assert.match(windows.stderr, /Herdr Desktop was not found/);
  assert.match(windows.stderr, /Node\.js is missing/);
  assert.match(windows.stderr, /Herdr Core was not found/);
  assert.equal(f.read(path.join(windowsHome, '.config/herdr-app/mods/pacafe-desktop/main.js')), 'first\n');
  assert.deepEqual(readdirSync(path.join(windowsHome, '.config/herdr-app')).sort(), ['mods']);
  f.checked(f.install([], { ...env, HERDR_APP_HOME: 'C:\\Users\\Fixture\\PA Cafe profile' }));
  assert.equal(f.read(path.join(windowsDestination, 'mods/pacafe-desktop/main.js')), 'first\n');
  assert.deepEqual(readdirSync(f.home), []);
});

test('only opt-in packaging builds the scanner from the selected commit and keeps prior files if it fails', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const source = path.join(f.repo, f.here, 'tools/tokscale-history');
  mkdirSync(source, { recursive: true });
  writeFileSync(path.join(source, 'Cargo.toml'), 'fixture manifest');
  writeFileSync(path.join(source, 'Cargo.lock'), 'locked fixture');
  f.commit('locked native scanner fixture');
  writeFileSync(path.join(source, 'Cargo.lock'), 'dirty checkout');
  writeFileSync(path.join(f.bin, 'cargo'), `#!/bin/bash
set -eu
[[ "$1 $2 $3 $4" == "build --locked --release --manifest-path" && "$6" == "--target-dir" ]]
[[ "$PWD" == /tmp/pacafe-check.* && "$(cat "\${5%/*}/Cargo.lock")" == 'locked fixture' ]]
printf 'build\\n' >> "$PA_FIXTURE_LOG.cargo"
[[ "\${PA_CARGO_FAIL-0}" != 1 ]] || exit 1
mkdir -p "$7/release"
name=pacafe-tokscale-history
case "$(uname -s)" in MINGW*) name="$name.exe" ;; esac
printf '#!/bin/sh\\n' > "$7/release/$name"
chmod +x "$7/release/$name"
`, { mode: 0o700 });
  f.checked(f.install());
  const scanner = path.join(f.installPath, 'bin/pacafe-tokscale-history');
  assert.equal(existsSync(scanner), false);
  assert.equal(existsSync(f.log + '.cargo'), false);
  const build = f.checked(f.install(['--with-usage']));
  assert.match(build, /Building optional/);
  assert.equal(f.read(scanner), '#!/bin/sh\n');
  assert.equal(f.read(f.log + '.cargo'), 'build\n');
  const failed = f.install(['--with-usage'], { PA_CARGO_FAIL: '1' });
  assert.equal(failed.status, 1);
  assert.match(failed.stderr, /installed mod was not changed/);
  assert.equal(f.read(scanner), '#!/bin/sh\n');
  assert.equal(f.read(path.join(source, 'Cargo.lock')), 'dirty checkout');
  f.checked(f.install());
  assert.equal(existsSync(scanner), false);

  // Exercise the Windows packaging branch on non-Windows CI. This verifies
  // the .exe layout and MSYS path handoff, not the Windows loader/toolchain.
  writeFileSync(path.join(f.bin, 'uname'), '#!/bin/bash\nprintf "MINGW64_NT-10.0\\n"\n', { mode: 0o700 });
  writeFileSync(path.join(f.bin, 'cygpath'), '#!/bin/bash\ncase "$1" in -au|-am) printf "%s\\n" "$3";; *) exit 2;; esac\n', { mode: 0o700 });
  const windows = { USERPROFILE: f.home, LOCALAPPDATA: '' };
  const winScanner = scanner + '.exe';
  assert.match(f.checked(f.install(['--with-usage'], windows)), /Building optional/);
  assert.equal(f.read(winScanner), '#!/bin/sh\n');
  assert.equal(existsSync(scanner), false);
  assert.equal(f.install(['--with-usage'], { ...windows, PA_CARGO_FAIL: '1' }).status, 1);
  assert.equal(f.read(winScanner), '#!/bin/sh\n');
});
